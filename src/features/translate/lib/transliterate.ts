function longestMatch(str: string, dict: Record<string, string>): { match: string; rest: string } | null {
  const keys = Object.keys(dict).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (str.toLowerCase().startsWith(key.toLowerCase())) {
      return { match: dict[key], rest: str.slice(key.length) };
    }
  }
  return null;
}

export function banglishToBangla(input: string): string {
  if (!input.trim()) return input;

  let result = input;

  // First apply known Banglish patterns (regex-based for common verb forms etc.)
  for (const [pattern, replacement] of BANGLISH_PATTERNS) {
    result = result.replace(pattern, replacement);
  }

  // Then check for common whole words/phrases
  for (const [banglish, bangla] of Object.entries(COMMON_WORDS)) {
    const regex = new RegExp(`\\b${escapeRegExp(banglish)}\\b`, "gi");
    result = result.replace(regex, bangla);
  }

  // Then do character-by-character transliteration for remaining
  return transliterateCharByChar(result);
}

function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function transliterateCharByChar(input: string): string {
  let result = "";
  let i = 0;
  const len = input.length;

  while (i < len) {
    const ch = input[i];
    const nextCh = i + 1 < len ? input[i + 1] : "";
    const nextTwoCh = i + 2 < len ? input[i + 2] : "";

    // Try 3-char consonant clusters first
    const threeChar = (ch + nextCh + nextTwoCh).toLowerCase();
    if (CONSONANTS[threeChar]) {
      result += CONSONANTS[threeChar];
      i += 3;
      continue;
    }

    // Try 2-char consonant clusters
    const twoChar = (ch + nextCh).toLowerCase();
    if (CONSONANTS[twoChar]) {
      const afterConsonant = i + 2 < len ? input[i + 2] : "";
      const vowelMatch = longestMatch(input.slice(i + 2), VOWEL_SIGNS);
      if (vowelMatch && vowelMatch.match !== "") {
        result += CONSONANTS[twoChar] + vowelMatch.match;
        const vowelKey = Object.keys(VOWEL_SIGNS).find(k => VOWEL_SIGNS[k] === vowelMatch.match);
        i += 2 + (vowelKey?.length || 1);
      } else {
        result += CONSONANTS[twoChar] + "া";
        i += 2;
      }
      continue;
    }

    // Single consonant
    const singleChar = ch.toLowerCase();
    if (CONSONANTS[singleChar]) {
      const afterConsonant = i + 1 < len ? input[i + 1] : "";
      const vowelMatch = longestMatch(input.slice(i + 1), VOWEL_SIGNS);
      if (vowelMatch && vowelMatch.match !== "") {
        result += CONSONANTS[singleChar] + vowelMatch.match;
        const vowelKey = Object.keys(VOWEL_SIGNS).find(k => VOWEL_SIGNS[k] === vowelMatch.match);
        i += 1 + (vowelKey?.length || 1);
      } else {
        const nextLower = nextCh.toLowerCase();
        if (VOWELS[nextLower] || VOWELS[nextCh + nextTwoCh]) {
          result += CONSONANTS[singleChar] + "া";
          i += 1;
        } else {
          if (i === len - 1 || /[^a-zA-Z]/.test(nextCh)) {
            result += CONSONANTS[singleChar];
          } else {
            result += CONSONANTS[singleChar] + "া";
          }
          i += 1;
        }
      }
      continue;
    }

    // Independent vowels
    const twoCharVowel = (ch + nextCh).toLowerCase();
    if (VOWELS[twoCharVowel]) {
      result += VOWELS[twoCharVowel];
      i += 2;
      continue;
    }
    const singleCharVowel = ch.toLowerCase();
    if (VOWELS[singleCharVowel]) {
      result += VOWELS[singleCharVowel];
      i += 1;
      continue;
    }

    // Numbers and punctuation - pass through
    if (/[0-9\s.,!?;:'"()-]/.test(ch)) {
      result += ch;
      i += 1;
      continue;
    }

    // Unknown char - pass through
    result += ch;
    i += 1;
  }

  return result;
}

// Enhanced search that tries both original query and transliterated Bangla
export function searchWithBanglishSupport(query: string, searchFn: (q: string) => any): any {
  const trimmed = query.trim();
  if (!trimmed) return searchFn("");

  // Try original query first
  const originalResult = searchFn(trimmed);

  // If original has results, return them
  if (originalResult.words?.length > 0 || originalResult.sentences?.length > 0) {
    return originalResult;
  }

  // Try transliterated Bangla
  const banglaQuery = banglishToBangla(trimmed);
  if (banglaQuery !== trimmed) {
    const transliteratedResult = searchFn(banglaQuery);
    return {
      words: [...new Set([...originalResult.words, ...transliteratedResult.words])],
      sentences: [...new Set([...originalResult.sentences, ...transliteratedResult.sentences])],
    };
  }

  return originalResult;
}

// Check if input looks like Banglish (mostly Latin chars with Bangla-like patterns)
export function isBanglish(input: string): boolean {
  const latinRatio = (input.match(/[a-zA-Z]/g) || []).length / input.length;
  const hasBanglaPattern = /(ami|tumi|apni|ki|kemon|kothay|keno|kivabe|bhalo|valo|khub|chai|jani|dekhi|shuni|kore|khabar|pani|cha|bhat|dal|torkari|mangsho|mach|dim|dudh|ruti|bari|ghor|kaaj|office|school|bazar|dukan|gari|bus|train|biman|ticket|hotel|time|shomoy|ekhon|aj|kal|gatkal|parsho|shokal|bikel|rat|dupur|bristi|dhup|megh|batash|garam|thanda|namaste|dhonnobad|swagatam|biday|abaro|ek|dui|tin|char|panch|chhoy|sat|aat|noy|dosh)/i.test(input);

  return latinRatio > 0.5 && hasBanglaPattern;
}